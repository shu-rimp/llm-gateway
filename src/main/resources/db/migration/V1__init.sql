CREATE TABLE eval_cases(
    id  BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question    TEXT    NOT NULL,
    reference_answer    TEXT    NOT NULL,
    must_contain    VARCHAR(200),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE eval_runs(
    id  BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_model    VARCHAR(100)    NOT NULL,
    judge_model VARCHAR(100)    NOT NULL,
    status  VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    started_at  TIMESTAMPTZ,
    finished_at TIMESTAMPTZ
);

CREATE TABLE eval_results(
    id  BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id  BIGINT  NOT NULL REFERENCES eval_runs(id),
    case_id BIGINT  NOT NULL REFERENCES eval_cases(id),
    answer  TEXT,
    latency_ms  INT,
    contains_pass   BOOLEAN,
    judge_score INT,
    judge_reason    TEXT,
    error   TEXT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    UNIQUE (run_id, case_id),
    CHECK (judge_score BETWEEN 1 AND 5)
);

